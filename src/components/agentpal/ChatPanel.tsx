"use client";

import { useEffect, useRef } from "react";
import {
  Sparkles,
  Bot,
  User,
  ImageIcon,
  Loader2,
  RotateCcw,
  Boxes,
  FileCode,
  FileType2,
  Code2,
} from "lucide-react";
import { useStore, type Msg, SUGGESTIONS } from "@/lib/studio/store";
import { parseSegments } from "@/lib/studio/artifacts";
import { themeGradient } from "@/lib/studio/themes";
import { THEMES } from "@/lib/studio/themes";
import Markdown, { SourcesList } from "./Markdown";
import { ArtifactCard } from "./ArtifactCanvas";

function Avatar({ role }: { role: "user" | "assistant" }) {
  const { theme } = useStore();
  const t = THEMES.find((x) => x.name === theme)!;
  if (role === "user") {
    return (
      <span
        className="grid h-7 w-7 shrink-0 place-items-center rounded-lg text-white"
        style={{ background: "var(--card)", border: "1px solid var(--line)", color: "var(--text)" }}
      >
        <User size={14} />
      </span>
    );
  }
  return (
    <span
      className="grid h-7 w-7 shrink-0 place-items-center rounded-lg text-white"
      style={{ background: themeGradient(t) }}
    >
      <Sparkles size={14} />
    </span>
  );
}

function StreamingDots() {
  return (
    <span className="typing">
      <span />
      <span />
      <span />
    </span>
  );
}

function MessageView({ msg, convId }: { msg: Msg; convId: string }) {
  const { activeArtifact, openArtifact, regenerateLast, streaming, conversations } = useStore();
  const isUser = msg.role === "user";

  if (isUser) {
    return (
      <div className="flex items-start gap-3 justify-end">
        <div className="bubble bubble-user max-w-[80%]">{msg.content}</div>
        <Avatar role="user" />
      </div>
    );
  }

  // image message
  if (msg.type === "image") {
    return (
      <div className="flex items-start gap-3">
        <Avatar role="assistant" />
        <div className="min-w-0 flex-1">
          {msg.streaming ? (
            <div
              className="flex items-center gap-2 rounded-2xl border px-4 py-3 text-sm"
              style={{ borderColor: "var(--line)", background: "var(--card)", color: "var(--muted)" }}
            >
              <Loader2 size={15} className="animate-spin" style={{ color: "var(--accent)" }} />
              Imagining your picture…
            </div>
          ) : (
            <div className="overflow-hidden rounded-2xl border" style={{ borderColor: "var(--line)" }}>
              <img src={msg.content} alt="Generated by AgentPaL" className="block max-w-full" />
            </div>
          )}
        </div>
      </div>
    );
  }

  // assistant text
  const segments = parseSegments(msg.content);
  const isEmpty = msg.streaming && !msg.content.trim();

  return (
    <div className="flex items-start gap-3">
      <Avatar role="assistant" />
      <div className="min-w-0 flex-1">
        {isEmpty ? (
          <div className="bubble bubble-assistant inline-flex items-center gap-2">
            <StreamingDots /> Pal is thinking…
          </div>
        ) : (
          <div className="bubble bubble-assistant">
            {segments.map((seg, i) =>
              seg.type === "text" ? (
                <div key={i}>
                  <Markdown>{seg.text}</Markdown>
                </div>
              ) : (
                <div key={i} className="my-2">
                  <ArtifactCard
                    artifact={seg.artifact}
                    active={
                      !!activeArtifact &&
                      activeArtifact.conversationId === convId &&
                      activeArtifact.messageId === msg.id
                    }
                    onOpen={() => openArtifact(convId, msg.id)}
                  />
                </div>
              )
            )}
            {msg.streaming && <span className="ml-0.5 inline-block h-3.5 w-1.5 animate-pulse align-middle" style={{ background: "var(--accent)" }} />}
            {msg.sources && msg.sources.length > 0 && <SourcesList sources={msg.sources} />}
          </div>
        )}
        {/* actions */}
        {!msg.streaming && !isEmpty && (
          <div className="mt-1.5 flex items-center gap-1 pl-1">
            <button
              onClick={() => regenerateLast()}
              disabled={streaming}
              className="flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[11px] transition-colors hover:bg-white/5 disabled:opacity-40"
              style={{ color: "var(--muted)" }}
              title="Regenerate response"
            >
              <RotateCcw size={11} /> Regenerate
            </button>
          </div>
        )}
      </div>
    </div>
  );
}

function WelcomeScreen() {
  const { composerMode, setComposerMode, sendMessage, sendImagine, theme } = useStore();
  const t = THEMES.find((x) => x.name === theme)!;

  const run = (text: string) => {
    if (composerMode === "imagine") sendImagine(text);
    else sendMessage(text);
  };

  return (
    <div className="flex min-h-full flex-col items-center justify-center px-4 py-10">
      <div className="w-full max-w-2xl text-center">
        <span
          className="floaty mx-auto grid h-16 w-16 place-items-center rounded-2xl text-white"
          style={{ background: themeGradient(t), boxShadow: "0 16px 40px -16px var(--glow)" }}
        >
          <Sparkles size={28} />
        </span>
        <h1 className="mt-5 text-3xl font-bold tracking-tight sm:text-4xl" style={{ color: "var(--text)" }}>
          Meet <span className="shimmer-text">Pal</span>
        </h1>
        <p className="mx-auto mt-3 max-w-md text-sm sm:text-base" style={{ color: "var(--muted)" }}>
          Your AI companion for everything. Chat, build live artifacts, imagine images, and
          search the web — all in one calm place.
        </p>

        {/* capability chips */}
        <div className="mt-5 flex flex-wrap items-center justify-center gap-2">
          {[
            { id: "chat", label: "Chat", icon: Bot },
            { id: "imagine", label: "Artifacts", icon: ImageIcon },
            { id: "search", label: "PayPal Docs", icon: FileCode },
          ].map((c) => {
            const Icon = c.icon;
            const active = composerMode === c.id;
            return (
              <button
                key={c.id}
                onClick={() => setComposerMode(c.id as any)}
                className="flex items-center gap-1.5 rounded-full border px-3 py-1.5 text-xs font-semibold transition-all"
                style={{
                  borderColor: active ? "transparent" : "var(--line)",
                  background: active ? themeGradient(t) : "var(--glass)",
                  color: active ? "#fff" : "var(--text)",
                }}
              >
                <Icon size={13} /> {c.label}
              </button>
            );
          })}
        </div>

        {/* suggestions */}
        <div className="mt-6 grid gap-2 text-left sm:grid-cols-2">
          {SUGGESTIONS.map((s) => (
            <button
              key={s}
              onClick={() => run(s)}
              className="glass-sm group flex items-center gap-3 p-3 text-left text-sm transition-all hover:-translate-y-0.5"
              style={{ color: "var(--text)" }}
            >
              <span
                className="grid h-7 w-7 shrink-0 place-items-center rounded-lg text-white"
                style={{ background: "linear-gradient(120deg, var(--accent), var(--accent2))" }}
              >
                <Sparkles size={13} />
              </span>
              <span className="leading-snug">{s}</span>
            </button>
          ))}
        </div>
      </div>
    </div>
  );
}

export default function ChatPanel() {
  const { activeConversationId, conversations } = useStore();
  const conv = conversations.find((c) => c.id === activeConversationId);
  const scrollRef = useRef<HTMLDivElement>(null);

  // auto-scroll on new content
  useEffect(() => {
    const el = scrollRef.current;
    if (!el) return;
    el.scrollTop = el.scrollHeight;
  }, [conv?.messages, activeConversationId]);

  return (
    <div className="flex min-w-0 flex-1 flex-col" style={{ background: "var(--bg)" }}>
      <div ref={scrollRef} className="scroll-thin flex-1 overflow-y-auto">
        {!conv || conv.messages.length === 0 ? (
          <WelcomeScreen />
        ) : (
          <div className="mx-auto flex max-w-3xl flex-col gap-5 px-4 py-6">
            {conv.messages.map((m) => (
              <MessageView key={m.id} msg={m} convId={conv.id} />
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
