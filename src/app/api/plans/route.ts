import { fail, ok, readJson } from "@/lib/http";
import { appendEvent } from "@/lib/events";
import { generatePlan } from "@/lib/planner";
import { updateStore } from "@/lib/store";

export const dynamic = "force-dynamic";

export async function GET() {
  const plans = await updateStore((s) => s.plans);
  return ok({ plans });
}

export async function POST(req: Request) {
  const body = await readJson<{ goal_id?: string; mandate_id?: string }>(req);
  try {
    const plan = await updateStore(async (store) => {
      // No "latest goal" fallback: the caller must name the goal explicitly.
      if (!body.goal_id) throw new Error("goal_id is required");
      const goal = store.goals.find((g) => g.goal_id === body.goal_id);
      if (!goal) throw new Error("Goal not found");
      const mandate =
        store.mandates.find((m) => m.mandate_id === body.mandate_id) ??
        store.mandates.find((m) => m.goal_id === goal.goal_id);
      if (!mandate) throw new Error("Mandate not found");
      const plan = await generatePlan(goal, mandate, store.merchants);
      store.plans.push(plan);
      appendEvent(store, "plan.generated", `Plan ${plan.plan_id} generated by ${plan.planner} planner`, {
        goal_id: goal.goal_id,
        plan_id: plan.plan_id,
        planner: plan.planner,
        model: plan.model,
        steps: plan.steps,
      });
      return plan;
    });
    return ok({ plan }, 201);
  } catch (err) {
    return fail(err instanceof Error ? err.message : "plan failed", 400);
  }
}
